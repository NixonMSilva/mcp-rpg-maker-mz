const SUBORDINATE_CODES = new Set<number>([401, 402, 403, 404, 405, 408, 411, 412, 413, 505, 601, 602, 603, 604, 605, 655, 657]);

/**
 * Continuation lines and branch markers belong to a preceding command at the
 * same indent and never start a block on their own. The engine's codes are
 * listed explicitly; unknown codes in 400-699 (the engine's subordinate
 * range) are treated the same way, other unknown codes (e.g. plugin-defined
 * 999) as standalone commands.
 */
export function isSubordinateCode(code: number): boolean {
  if (SUBORDINATE_CODES.has(code)) return true;
  return code >= 400 && code < 700 && !Object.prototype.hasOwnProperty.call(COMMAND_NAMES, code);
}

/** Codes known to the engine (anything else is plugin-defined or corrupt). */
export function isKnownCode(code: number): boolean {
  return Object.prototype.hasOwnProperty.call(COMMAND_NAMES, code);
}

