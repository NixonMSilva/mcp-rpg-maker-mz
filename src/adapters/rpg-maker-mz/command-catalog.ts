const ROUTE_BY_CODE = new Map(ROUTE_COMMANDS.map((r) => [r.code, r]));
const ROUTE_BY_NAME = new Map(ROUTE_COMMANDS.map((r) => [r.name, r]));

export function routeCommandByCode(code: number): RouteCommandDef | undefined {
  return ROUTE_BY_CODE.get(code);
}

export function routeCommandByName(name: string): RouteCommandDef | undefined {
  return ROUTE_BY_NAME.get(name.toLowerCase().replace(/[\s-]+/g, "_"));
}
